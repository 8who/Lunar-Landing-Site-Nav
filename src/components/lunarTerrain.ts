import * as THREE from 'three'
import { elevationAt, isotropicGrid } from '../lib/astro/terrain'
import type { LunarSite } from '../lib/astro/types'

/** Periodic value noise: coherent grains and worn relief without sinusoidal ridges. */
function noise(x: number, y: number, period = 256) {
  const hash = (a: number, b: number) => {
    a = ((a % period) + period) % period
    b = ((b % period) + period) % period
    let h = Math.imul(a + 173, 374761393) ^ Math.imul(b + 29, 668265263)
    h = Math.imul(h ^ (h >>> 13), 1274126177)
    return ((h ^ (h >>> 16)) >>> 0) / 4294967296
  }
  const ix = Math.floor(x), iy = Math.floor(y)
  const smooth = (t: number) => t * t * t * (t * (t * 6 - 15) + 10)
  const u = smooth(x - ix), v = smooth(y - iy)
  return THREE.MathUtils.lerp(THREE.MathUtils.lerp(hash(ix, iy), hash(ix + 1, iy), u),
    THREE.MathUtils.lerp(hash(ix, iy + 1), hash(ix + 1, iy + 1), u), v)
}

// Reuse the generated bytes on site changes; each scene owns its GPU texture.
let surfacePixels: Uint8Array | null = null
/** R: physical micro-height, G: roughness, B: subtle albedo variation. No baked shadows. */
function makeSurfaceDetail() {
  const size = 1024
  if (!surfacePixels) {
    const heights = new Float32Array(size * size)
    for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
      heights[y * size + x] = 0.5
        + 0.18 * (noise(x / 64, y / 64, 16) - 0.5)
        + 0.13 * (noise(x / 16, y / 16, 64) - 0.5)
        + 0.09 * (noise(x / 4, y / 4) - 0.5)
        + 0.035 * (noise(x, y, size) - 0.5)
    }
    let seed = 48127
    const random = () => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296 }
    // Many small impacts, fewer broad ones. Irregular rims merge into the soil.
    for (let i = 0; i < 620; i++) {
      const cx = random() * size, cy = random() * size
      const radius = 2 + Math.pow(random(), 3) * 42
      const stretch = 0.8 + random() * 0.4, phase = random() * Math.PI * 2
      const bound = Math.ceil(radius * 1.65)
      for (let dy = -bound; dy <= bound; dy++) for (let dx = -bound; dx <= bound; dx++) {
        const angle = Math.atan2(dy, dx)
        const r = Math.hypot(dx * stretch, dy / stretch) / radius
          * (1 + 0.06 * Math.sin(angle * 5 + phase) + 0.04 * Math.sin(angle * 9 - phase))
        if (r > 1.5) continue
        const index = ((Math.floor(cy) + dy + size) % size) * size + (Math.floor(cx) + dx + size) % size
        heights[index] += 0.10 * Math.exp(-(((r - 1) / 0.19) ** 2))
          - 0.22 * Math.exp(-((r / 0.65) ** 2))
      }
    }
    surfacePixels = new Uint8Array(size * size * 4)
    for (let i = 0; i < heights.length; i++) {
      const h = THREE.MathUtils.clamp(heights[i], 0, 1)
      surfacePixels[i * 4] = Math.round(h * 255)
      surfacePixels[i * 4 + 1] = Math.round(244 + h * 10)
      surfacePixels[i * 4 + 2] = Math.round(94 + h * 66)
      surfacePixels[i * 4 + 3] = 255
    }
  }
  const texture = new THREE.DataTexture(surfacePixels, size, size)
  texture.wrapS = texture.wrapT = THREE.RepeatWrapping
  texture.magFilter = THREE.LinearFilter
  texture.minFilter = THREE.LinearMipmapLinearFilter
  texture.generateMipmaps = true
  texture.channel = 1
  texture.needsUpdate = true
  return texture
}

/** Regional terrain patch, 300 km across; scene scale 0.1 units per km. */
export function createLunarTerrain(grid: Float32Array, site: LunarSite, map: THREE.Texture) {
  grid = isotropicGrid(grid)
  const rad = Math.PI / 180, lat = site.lat * rad, lon = site.lon * rad
  const up = new THREE.Vector3(Math.cos(lat)*Math.cos(lon), Math.cos(lat)*Math.sin(lon), Math.sin(lat))
  const east = new THREE.Vector3(-Math.sin(lon), Math.cos(lon), 0)
  const north = new THREE.Vector3().crossVectors(up, east)
  const base = 1737.4 + elevationAt(grid, site.lat, site.lon)
  // Concentrate vertices around the observer while retaining the 300 km extent.
  const geometry = new THREE.PlaneGeometry(300, 300, 384, 384)
  const positions = geometry.getAttribute('position'), uv = geometry.getAttribute('uv')
  const detailUv = new Float32Array(positions.count * 2)
  const craters = [[18, 24, 7], [-27, 16, 10], [36, -22, 6], [-13, -32, 5], [42, 8, 3], [-43, -18, 4], [5, -49, 8], [-52, 37, 5]]
  const detailHeight = (e: number, n: number) => {
    const x = e * 1000, z = n * 1000, distance = Math.hypot(x,z)
    const fade = 1 - THREE.MathUtils.smoothstep(distance, 60, 120)
    // Metre-scale illustrative terrain, fading smoothly into measured relief.
    let h = 0.08 * (noise(x / 1.7, z / 1.7) - 0.5)
      + 0.28 * (noise(x / 7, z / 7) - 0.5)
      + 0.65 * (noise(x / 23, z / 23) - 0.5)
    for (const [cx, cz, radius] of craters) {
      const angle = Math.atan2(z - cz, x - cx)
      const r = Math.hypot(x-cx,z-cz) / radius * (1 + 0.07 * Math.sin(angle * 5 + cx))
      h += 0.28 * Math.exp(-(((r-1)/0.18)**2)) - 0.65 * Math.exp(-((r/0.7)**2))
    }
    return h * fade / 1000
  }
  const originDetail = detailHeight(0,0)
  const surface = (e: number, n: number) => {
    const direction = up.clone().multiplyScalar(1737.4).addScaledVector(east,e).addScaledVector(north,n).normalize()
    const latitude = Math.asin(direction.z) / rad, longitude = Math.atan2(direction.y,direction.x) / rad
    const point = direction.multiplyScalar(1737.4 + elevationAt(grid,latitude,longitude)).addScaledVector(up,-base)
    return { latitude, longitude, position: new THREE.Vector3(point.dot(east)*0.1,
      (point.dot(up)+detailHeight(e,n)-originDetail-(site.mastHeightM ?? 0)/1000)*0.1-0.0002, -point.dot(north)*0.1) }
  }
  for (let i = 0; i < positions.count; i++) {
    const warp = (v: number) => Math.sign(v) * Math.pow(Math.abs(v)/150,3) * 150
    const e = warp(positions.getX(i)), n = warp(positions.getY(i))
    const { latitude, longitude, position } = surface(e,n)
    const edge = Math.max(Math.abs(positions.getX(i)), Math.abs(positions.getY(i)))
    position.y *= 1 - THREE.MathUtils.smoothstep(edge, 142, 150)
    positions.setXYZ(i,position.x,position.y,position.z)
    const delta = ((longitude-site.lon+540)%360)-180
    uv.setXY(i,(site.lon+delta+180)/360,(latitude+90)/180)
    detailUv[i*2] = e / 0.012
    detailUv[i*2+1] = n / 0.012
  }
  geometry.setAttribute('uv1',new THREE.BufferAttribute(detailUv,2))
  geometry.computeVertexNormals()
  const detail = makeSurfaceDetail()
  detail.anisotropy = map.anisotropy
  const material = new THREE.MeshStandardMaterial({
    map, bumpMap: detail, roughnessMap: detail, bumpScale: 0.000025,
    roughness: 1, metalness: 0, side: THREE.DoubleSide, transparent: true,
  })
  // Couple albedo and relief so pits belong to the ground. Derivative-filtered
  // mipmaps keep fine grain quiet at grazing angles and on mobile displays.
  material.onBeforeCompile = shader => {
    shader.fragmentShader = shader.fragmentShader.replace('#include <map_fragment>', `
      #include <map_fragment>
      float soil = texture2D(bumpMap, vBumpMapUv).b * 2.0;
      float grain = texture2D(bumpMap, vBumpMapUv * 7.13 + vec2(0.37, 0.61)).b * 2.0;
      diffuseColor.rgb *= soil * mix(1.0, grain, 0.35);
    `)
  }
  material.customProgramCacheKey = () => 'lunar-regolith-v1'
  const mesh = new THREE.Mesh(geometry,material)
  mesh.renderOrder = 11
  geometry.computeBoundingSphere()
  return mesh
}
